async def infer(name, **inputs):
    from pyodide.ffi import to_js
    from js import Object, run_model
    packed={k:dict(data=memoryview(np.ascontiguousarray(v,dtype=np.float32).ravel()),dims=list(v.shape)) for k,v in inputs.items()}
    out=await run_model(name,to_js(packed,dict_converter=Object.fromEntries))
    values=out.to_py()
    return {k:np.asarray(v['data'],dtype=np.float32).reshape(v['dims']).copy() for k,v in values.items()}

def progress(value,text):
    from js import report_progress
    report_progress(value,text)

def namespace(code,settings):
    ns=dict(globals());ns.update(settings);exec(code,ns);return ns

class BrowserPipeline:
    def __init__(self,manifest):
        if manifest.get('operator_source_sha256')!=OPS['source_sha256']:
            raise ValueError('모델 변환기와 웹페이지의 전·후처리 버전이 다릅니다. 같은 버전의 변환기를 사용하세요.')
        self.meta=manifest;self.last=None;self.mask=None;self.fh_masks=None
        nc=manifest['number'];ac=manifest['a']
        n=dict(INPUT_H=nc['input_h'],INPUT_W=nc['input_w'],ROI_CONTEXT_SCALE_X=nc['roi_context_scale_x'],
            ROI_CONTEXT_SCALE_Y=nc['roi_context_scale_y'],NUM_CLASSES=len(nc['levels']),VITERBI_EPS=1e-8,
            FRAGMENT_AREA_RATIO=.05,WS_MIN_CHILD_RATIO=.15,WS_PEAK_DISTANCE_RATIO=.5,
            WS_PEAK_HEIGHT_RATIO=.25,WS_PROMINENCE_RATIO=.15,WS_VALLEY_RATIO=.75)
        self.sp=namespace(OPS['spine']+'\n'+OPS['watershed'],n)
        seg={k:ac[v] for k,v in OPS['seg_key_map'].items()};seg.update(MAX_DYNAMIC_PATCHES=6,IMAGENET_MEAN=MEAN,IMAGENET_STD=STD)
        self.seg=namespace(OPS['seg'],seg)
        self.fh=namespace(OPS['fh'],manifest['fh'])
        self.s1=namespace(OPS['s1'],manifest['s1'])

    async def segment(self,path):
        s=self.seg;gray=s['read_gray'](path);h,w=gray.shape
        ranges=s['compute_fixed_patch_ranges'](h,w)
        sums=np.zeros((h,w),np.float32);weights=np.zeros_like(sums)
        # GN is independent of batch size; one patch avoids browser memory spikes.
        for i,(_,y0,y1) in enumerate(ranges):
            progress(10+23*i/len(ranges),f'척추 분할 {i+1}/{len(ranges)}')
            patch=cv2.resize(gray[y0:y1],(s['MODEL_WIDTH'],s['MODEL_HEIGHT']),interpolation=cv2.INTER_LINEAR)
            x=s['make_model_input'](patch,s['make_global_y_map'](y0,y1,h))
            p=(await infer('a',image=x[None]))['probabilities'][0,0]
            source=cv2.resize(p,(w,y1-y0),interpolation=cv2.INTER_LINEAR)
            weight=s['make_source_blend_weight'](ranges,i,w)[0]
            sums[y0:y1]+=source*weight;weights[y0:y1]+=weight
        mask=(np.clip(sums/np.clip(weights,1e-7,None),0,1)>=.5).astype(np.uint8)
        progress(34,'파편 제거 · watershed')
        return mask,self.sp['extract_watershed_polygons'](mask)

    async def number(self,path,polys):
        if not polys:return [],'raw','no_candidates'
        ns=self.sp;cfg=self.meta['number'];sc=self.meta['scaler']
        image=ns['read_normalized_xray'](path);h,w=image.shape;lb,tr=ns['letterbox_image'](image)
        rgb=(np.repeat(lb[...,None],3,axis=2)-MEAN)/STD
        candidates=[]
        for i,p in enumerate(polys):
            pts=np.asarray(p['points'],np.float32);features,aux=ns['polygon_basic_geometry'](pts,float(w),float(h))
            features.update(ns['view_features']('LAT'))
            geometry=np.asarray([features[k] for k in cfg['feature_names']],np.float32)
            if sc['mean'] is not None:geometry-=np.asarray(sc['mean'],np.float64)
            if sc['scale'] is not None:geometry/=np.asarray(sc['scale'],np.float64)
            box=ns['transform_box_to_letterbox'](ns['context_bbox_from_points'](pts,w,h),tr)
            candidates.append(dict(input_index=i,cy=float(aux['cy']),box=box,geometry=geometry))
        candidates.sort(key=lambda c:c['cy'])
        out=await infer('number',image=rgb.transpose(2,0,1)[None],boxes=np.stack([c['box'] for c in candidates]),geometry=np.stack([c['geometry'] for c in candidates]))
        prob=out['probabilities'];n=len(candidates)
        if prob.shape!=(n,23) or not np.isfinite(prob).all():raise ValueError('번호 모델 출력 형태 오류')
        raw=prob.argmax(1);vit=ns['viterbi_decode_monotonic'](prob,skip_penalty=cfg['best_viterbi_penalty']) if n<=23 else None
        decoder='viterbi' if vit is not None else 'raw';rows=[]
        for i,c in enumerate(candidates):
            j=int(vit[i] if vit is not None else raw[i]);levels=cfg['levels']
            rows.append(dict(input_index=c['input_index'],cy=c['cy'],raw_level=levels[int(raw[i])],raw_confidence=float(prob[i,raw[i]]),
                viterbi_level=levels[int(vit[i])] if vit is not None else None,viterbi_confidence=float(prob[i,vit[i]]) if vit is not None else None,
                final_level=levels[j],final_confidence=float(prob[i,j]),final_decoder=decoder))
        return rows,decoder,None if vit is not None else 'candidate_count_exceeds_23'

    async def s1_predict(self,path,polygon):
        s=self.s1;a=s['read_gray'](path);p=np.asarray(polygon,float).reshape(-1,2)
        if len(p)<3 or not np.isfinite(p).all() or abs(cv2.contourArea(p.astype('float32')))<=1:raise ValueError('L5 윤곽 오류')
        if not ((p>=0).all() and (p[:,0]<a.shape[1]).all() and (p[:,1]<a.shape[0]).all()):raise ValueError('L5 윤곽이 영상 밖에 있습니다.')
        c=dict(width=a.shape[1],height=a.shape[0],l5=p.tolist())
        full,_=s['make_letterbox'](a,s['CFG']['coarse_hw'])
        rgb=(np.repeat(full[None],3,0)-MEAN[:,None,None])/STD[:,None,None]
        feature=(await infer('s1_coarse',image=rgb[None]))['context']
        mat=s['geom'](p);h,w=s['H'],s['W']
        crop=cv2.warpAffine(a,mat[:2],(w,h),flags=cv2.INTER_LINEAR)
        mask=np.zeros((h,w),np.uint8);cv2.fillPoly(mask,[np.rint(s['xy'](p,mat)).astype('int32')],1)
        rgb=(np.repeat(crop[None],3,0)-np.array([.485,.456,.406])[:,None,None])/np.array([.229,.224,.225])[:,None,None]
        x=np.concatenate([rgb,mask[None]],0).astype(np.float32)
        corners=s['xy']([[0,0],[w-1,0],[0,h-1],[w-1,h-1]],np.linalg.inv(mat))
        pos=(2*(corners+.5)/[c['width'],c['height']]-1).ravel().astype(np.float32)
        maps=(await infer('s1_fine',image=x[None],context=feature,position=pos[None]))['probabilities'][0]
        mapping,valid=s['heatmap_geometry'](c,mat,maps.shape[-2:]);points=[]
        # Original decode_l5: log-parabolic subpixel refinement on the valid region.
        for heat in maps:
            y,x=np.unravel_index(np.where(valid,heat,-1).argmax(),heat.shape);q=[float(x),float(y)]
            for axis,(dx,dy) in enumerate(((1,0),(0,1))):
                if not (0<=x-dx and x+dx<heat.shape[1] and 0<=y-dy and y+dy<heat.shape[0]):continue
                if not(valid[y-dy,x-dx] and valid[y+dy,x+dx]):continue
                a0,b0,d0=np.log(np.maximum([heat[y-dy,x-dx],heat[y,x],heat[y+dy,x+dx]],1e-8));curve=a0-2*b0+d0
                if curve < -1e-8:q[axis]+=float(np.clip(.5*(a0-d0)/curve,-.5,.5))
            points.append(q)
        baseline=s['xy'](points,np.linalg.inv(mapping))
        bank=s['build_pair_bank'](maps,baseline,c,mat,s['PRIOR'],s['PC'])
        pred,index=s['choose_pair'](bank,s['SELECTION']['strength'])
        return dict(points=pred.tolist(),original_points=baseline.tolist(),strength=s['SELECTION']['strength'],selected_pair=index)

    async def model_crop(self,stage,gray,roi,size):
        s=self.fh;x0,y0,x1,y1=map(int,roi)
        image,_,_,info=s['letterbox'](gray[y0:y1,x0:x1],[],size)
        out=await infer(stage,image=s['normalize'](image)[None])
        restored=np.stack([s['undo_letterbox'](p,info) for p in out['probabilities'][0]])
        return restored,out['count'][0] if 'count' in out else None

    async def femoral(self,path):
        s=self.fh;gray=s['read_gray'](path);h,w=gray.shape;lower=[0,int(h*s['CROP_TOP_RATIO']),w,h]
        p,_=await self.model_crop('fh_coarse',gray,lower,s['COARSE_SIZE'])
        binary=p[0]>=s['ROI_PROPOSAL_THRESHOLD'];lab,n=ndi.label(binary);areas=np.bincount(lab.ravel());areas[0]=0
        ids=sorted(range(1,len(areas)),key=lambda i:areas[i],reverse=True)[:2]
        ids=[i for i in ids if areas[i]>=max(8,int(binary.size*s['MIN_REGION_FRACTION']))]
        full=np.zeros((h,w),bool);full[lower[1]:]=np.isin(lab,ids) if ids else False
        roi=s['bbox_roi'](full);found=bool(ids)
        prob,cp=await self.model_crop('fh_fine',gray,roi,s['FINE_SIZE'])
        circles,masks=s['circles_from_slots'](prob,s['threshold'],roi);outcome=s['hc_result'](circles,cp)
        if not found:outcome['review_reasons'].append('coarse_not_detected_fallback');outcome['HC_LAT']=None
        if outcome['review_reasons']:outcome['status']='review_required'
        polygons=[];contours=[]
        for i,c in enumerate(circles):
            t=np.arange(32)*2*np.pi/32;pts=np.column_stack([c['cx']+c['radius']*np.cos(t),c['cy']+c['radius']*np.sin(t)])
            polygons.append(dict(id=f'ai_fh_lat_{i+1}',label='FH_LAT',shape='circle',source='ai_fh_v2',points=pts.ravel().tolist()))
        for slot,mask in enumerate(masks):
            cs,_=cv2.findContours(mask.astype(np.uint8),cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
            for c in cs:
                if len(c)>=3:contours.append(dict(slot=slot,points=(c.reshape(-1,2)+roi[:2]).tolist()))
        return dict(image=Path(path).name,instances=circles,annotator_polygons=polygons,roi=list(map(int,roi)),
                    coarse_found=found,threshold=s['threshold'],segmentation_contours=contours,**outcome),masks.astype(np.uint8)

    def refresh(self):
        r=self.last
        pending=r.get('s1',{}).get('status') not in ('predicted',None) or r.get('femoral',{}).get('status') in ('review_required','failed')
        corners=any(c.get(m,{}).get('quality')=='review' for c in r.get('spine',{}).get('corners',[]) for m in ('v1','v2'))
        r['status']='partial' if r['errors'] else 'review_required' if pending or corners or r['review_reasons'] else 'complete'

    async def run_s1(self,index=None):
        r=self.last;r['errors']=[e for e in r['errors'] if e['stage']!='s1'];polys=r['spine']['polygons']
        choices=[x['input_index'] for x in r['spine']['numbering'] if x['final_level']=='L5'];manual=index is not None
        if index is None:
            if len(choices)!=1:
                r['s1']=dict(status='needs_l5_selection',points=None,l5_candidates=choices,reason='L5가 없습니다.' if not choices else 'L5 후보가 여러 개입니다.')
                self.refresh();return
            index=choices[0]
        if not isinstance(index,int) or not 0<=index<len(polys):raise ValueError('유효하지 않은 L5 후보')
        try:
            pred=await self.s1_predict(self.path,polys[index]['points']);pts=np.asarray(pred['points'])
            if pts.shape!=(2,2) or not np.isfinite(pts).all():raise ValueError('S1 끝점 오류')
            ok=bool((pts>=0).all() and (pts[:,0]<r['image']['width']).all() and (pts[:,1]<r['image']['height']).all())
            r['s1']=dict(**pred,status='predicted' if ok else 'review_required',in_bounds=ok,l5_candidate_index=index,
                l5_source='user_selected_prediction' if manual else 'unique_predicted_L5')
        except Exception as e:
            r['s1']=dict(status='failed',points=None,l5_candidate_index=index);r['errors'].append(dict(stage='s1',message=str(e)))
        self.refresh()

    async def predict(self,path,filename,anterior_right,sha256):
        from js import run_corners
        self.path=path;start=time.perf_counter();self.mask=None;self.fh_masks=None;self.last=None
        with Image.open(path) as im:
            if getattr(im,'n_frames',1)!=1:raise ValueError('단일 영상만 지원합니다.')
            w,h=im.size
            if w*h>32_000_000:raise ValueError('브라우저에서는 3,200만 화소 이하 영상을 사용하세요.')
        r=dict(schema_version='spine-unified-ui-1',image=dict(filename=filename,width=w,height=h,sha256=sha256,orientation='original_array_no_exif_rotation'),
            anterior_right=anterior_right,status='processing',errors=[],review_reasons=list(self.meta['provenance'].get('notes',[])),timings={})
        self.last=r
        self.mask,polys=await self.segment(path);r['timings']['segmentation_seconds']=time.perf_counter()-start;t=time.perf_counter()
        progress(38,'척추 번호 예측');rows,decoder,reason=await self.number(path,polys)
        r['spine']=dict(polygons=to_jsonable(polys),numbering=rows,decoder=decoder,fallback_reason=reason)
        if reason:r['review_reasons'].append('번호 보정: '+reason)
        labels=[x['final_level'] for x in rows];duplicates=sorted({l for l in labels if labels.count(l)>1})
        if duplicates:r['review_reasons'].append('중복 번호: '+', '.join(duplicates))
        r['timings']['numbering_seconds']=time.perf_counter()-t;t=time.perf_counter();progress(50,'Annotator v1/v2 꼭지점')
        try:r['spine']['corners']=json.loads(run_corners(json.dumps(r['spine']),w,anterior_right))
        except Exception as e:r['spine']['corners']=[];r['errors'].append(dict(stage='corners',message=str(e)))
        r['timings']['corners_seconds']=time.perf_counter()-t;t=time.perf_counter();progress(62,'S1 상종판')
        await self.run_s1();r['timings']['s1_seconds']=time.perf_counter()-t;t=time.perf_counter();progress(78,'대퇴골두 분할 · 중심')
        try:r['femoral'],self.fh_masks=await self.femoral(path)
        except Exception as e:
            r['femoral']=dict(status='failed',instances=[],HC_LAT=None,review_reasons=['추론 실패'],segmentation_contours=[])
            r['errors'].append(dict(stage='femoral',message=str(e)))
        r['timings']['femoral_seconds']=time.perf_counter()-t;r['timings']['total_seconds']=time.perf_counter()-start
        r['models']=dict(bundle=self.meta.get('bundle_sha256'),provenance=self.meta['provenance'],runtime='browser',validation=self.meta.get('browser_validation'))
        self.refresh();progress(100,'분석 완료');return json.dumps(to_jsonable(r),ensure_ascii=False,allow_nan=False)

